#!/usr/bin/env bash
# Режим разработки: бэкенд (:8787) + прокси трафика (:8788) запускаются вместе с фронтендом next dev (:5173).
# /api фронтенда проксируется на бэкенд; Ctrl-C завершает оба процесса.
#
# Про режим единого бинарника (со встроенным фронтендом) см. раздел README
# «Способ 4: сборка единого бинарника из исходного кода» — этот скрипт его не использует.
set -euo pipefail
cd "$(dirname "$0")"

# При выходе завершаем все процессы этой группы (бэкенд + фронтенд).
cleanup() { kill 0 2>/dev/null || true; }
trap cleanup EXIT INT TERM

# Бэкенд (обычный go run, без встроенного фронтенда); число параллельных worker-агентов настраивается в «Системных настройках».
go run ./cmd/artex -addr :8787 -proxy 127.0.0.1:8788 &

# Горячее обновление фронтенда (дев-сервер Next, /api проксируется на :8787).
( cd web && npm run dev ) &

echo "[dev] бэкенд :8787 / прокси :8788 / фронтенд http://localhost:5173  (Ctrl-C для выхода)"
wait
