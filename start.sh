#!/bin/sh
# Скрипт-супервизор запуска ARTEX (Linux / macOS / Docker ENTRYPOINT)
#
# Использование:
#   ./start.sh                       запуск на переднем плане (Ctrl-C для остановки)
#   nohup ./start.sh >artex.log 2>&1 &   постоянная работа в фоне
#   ./start.sh -addr :9000           дополнительные параметры передаются в artex без изменений
#
# Он делает только одно: запускает artex, а после завершения процесса по коду
# выхода решает, нужно ли перезапускать.
#
#   0      пользователь штатно остановил   → выход из цикла
#   75     программа запросила перезапуск  → немедленный перезапуск (нажали
#          "обновление в один клик" или "откат" на странице)
#   прочее сбой                            → перезапуск с задержкой (1→2→4… максимум 60 секунд)
#
# Намеренно не делаем здесь загрузку, проверку SHA256 или замену бинарника: эту
# логику пришлось бы писать дважды — для sh и для bat, а это именно тот участок,
# где ошибка недопустима — если подменить на нерабочий бинарник, этот скрипт
# честно будет пытаться его перезапускать снова и снова, и исправить это
# сможет только человек за консолью. Поэтому вся проверка/замена остаётся в Go
# (пакет selfupdate) — artex сам выполняет это при запуске, а скрипт остаётся максимально простым.
set -u

cd "$(dirname "$0")" || exit 1

BIN=./artex
[ -x "$BIN" ] || { echo "[artex] исполняемый файл не найден: $BIN" >&2; exit 1; }

RESTART_CODE=75
MAX_DELAY=60

child=0
stopping=0

# Пересылает сигнал остановки процессу artex.
#
# Это необходимо в Docker: docker stop отправляет SIGTERM только PID 1 (то есть
# этому скрипту), а не дочернему процессу. Без пересылки artex не получит
# сигнал и не сможет корректно завершиться — через 10 секунд его убьёт
# SIGKILL, и выполняющиеся задачи прервутся на середине.
forward() {
	stopping=1
	if [ "$child" -ne 0 ]; then
		kill -TERM "$child" 2>/dev/null || true
	fi
}
trap forward INT TERM

delay=1
while :; do
	"$BIN" "$@" &
	child=$!

	# Сигнал прерывает wait и заставляет его вернуть код >128. В этот момент
	# дочерний процесс ещё выполняет корректное завершение, поэтому нужно
	# вызвать wait ещё раз, чтобы получить его настоящий код выхода.
	wait "$child"
	code=$?
	if [ "$code" -gt 128 ]; then
		wait "$child"
		code=$?
	fi
	child=0

	if [ "$stopping" -eq 1 ]; then
		echo "[artex] остановлен"
		exit 0
	fi

	case "$code" in
		0)
			echo "[artex] штатное завершение"
			exit 0
			;;
		"$RESTART_CODE")
			# Обновление/откат готовы: после перезапуска artex сам завершит замену бинарника при старте (см. selfupdate.Bootstrap).
			echo "[artex] запрошен перезапуск (применение новой версии)…"
			delay=1
			;;
		*)
			echo "[artex] аварийное завершение (code=$code), перезапуск через ${delay}с" >&2
			sleep "$delay"
			delay=$((delay * 2))
			[ "$delay" -gt "$MAX_DELAY" ] && delay=$MAX_DELAY
			;;
	esac
done
